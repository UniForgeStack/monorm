// Derives prisma/schema.prisma from the shared ../schema.prisma: Prisma has no `through:` relation and no
// timestamptz default, so the two many-to-many fields go (the explicit PostTag model stays) and DateTime gets @db.Timestamptz(6).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const shared = readFileSync(join(here, "..", "schema.prisma"), "utf8");
const body = shared
  .split("\n")
  .filter(l => !l.includes("@relation(through:"))
  .map(l => (/^\s+\w+\s+DateTime\s*$/.test(l) ? `${l.trimEnd()} @db.Timestamptz(6)` : l))
  .join("\n")
  .replace(/datasource db \{[^}]*\}/, "");
const header = `// Generated by make-prisma-schema.mjs from ../../schema.prisma. Do not edit.
generator client {
  provider = "prisma-client"
  output   = "../generated"
}

datasource db {
  provider = "postgresql"
}
`;
writeFileSync(join(here, "prisma", "schema.prisma"), header + body);
