// Extension language code at runtime. The default native artifact has no extension, so the
// artifact record is faked; the files and `define()` are real.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { pathToFileURL } from "node:url";
import { define, QuerySet, Registry, useQuerySet } from "../src/index.js";
import { InstanceBase } from "../src/ext.js";
import { call, native } from "../src/native.js";

const source = `
model Post {
  id Int @id
  title String
}
model Tag {
  id Int @id
}
`;

type Ctor = new (...args: any[]) => QuerySet<never>;
const mixinA = (Base: Ctor) => class extends (Base as Ctor & { prototype: { chain(): string[] } }) {
  everything() { return (this as never as { withoutDefaults(): unknown }).withoutDefaults(); }
  chain() { return ["a"]; }
};
const mixinB = (Base: Ctor) => class extends (Base as unknown as new (...args: any[]) => { chain(): string[] }) {
  override chain() { return ["b", ...super.chain()]; }
};
class AInstance { label() { return `a${String((this as never as { pk: unknown }).pk)}`; } }

function digest(files: [string, string][]): string {
  const sha = createHash("sha256");
  const len = (n: number) => { const b = Buffer.alloc(8); b.writeBigUInt64LE(BigInt(n)); return b; };
  for (const [name, text] of files) sha.update(len(Buffer.byteLength(name))).update(name).update(len(Buffer.byteLength(text))).update(text);
  return sha.digest("hex");
}

function record(extension: string, hash: string, changes: object = {}) {
  return {
    extension, version: "1.0.0", language: "typescript", query_set: "queries", instance: "Instance",
    query_set_members: ["chain", "everything"], instance_members: ["label"], overrides: [], hash, ...changes,
  };
}

function project(extension = "ext.a", changes: object = {}, text = "export const a = 1;\n") {
  const root = mkdtempSync(join(tmpdir(), "orm-ext-"));
  mkdirSync(join(root, "ext-a"));
  const hash = digest([["index.ts", text]]);
  const header = `// Generated by \`orm generate\` from extension ${extension}. Do not edit.\n// orm-ext ${extension} 1.0.0 ${hash}\n\n`;
  writeFileSync(join(root, "ext-a", "index.ts"), header + text);
  return { root, hash, dir: pathToFileURL(join(root, "ext-a") + "/"), records: [record(extension, hash, changes)] };
}

function build(records: object[], extensions: object, members: object) {
  const addon = native() as unknown as { nativeArtifact: () => string };
  const original = addon.nativeArtifact;
  addon.nativeArtifact = () => JSON.stringify({ ...JSON.parse(original.call(addon)), language_members: records });
  try {
    return define(call(() => native().compileSchema(source, null)), { registry: new Registry(), extensions, members } as never);
  } finally {
    addon.nativeArtifact = original;
  }
}

const code = (p: { hash: string; dir: URL }, module: object = { queries: mixinA, Instance: AInstance }) => ({ "ext.a": { module, hash: p.hash, dir: p.dir } });

test("members reach only the models that use the extension", () => {
  const p = project();
  const { Post, Tag } = build(p.records, code(p), { Post: ["ext.a"] }) as Record<string, any>;
  assert.deepEqual(Post.objects.chain(), ["a"]);
  assert.equal(typeof Post.objects.everything, "function");
  assert.equal(Tag.objects.chain, undefined);
  assert.equal("label" in Post._meta.Row.prototype, true);
  assert.equal("label" in Tag._meta.Row.prototype, false);
});

test("two mixins chain through super in dependency order", () => {
  const p = project();
  const records = [...p.records, record("ext.b", p.hash, { query_set_members: ["chain"], instance_members: [], overrides: ["chain"] })];
  const extensions = { ...code(p), "ext.b": { module: { queries: mixinB, Instance: class {} }, hash: p.hash, dir: new URL("file:///nowhere/") } };
  const { Post } = build(records, extensions, { Post: ["ext.a", "ext.b"] }) as Record<string, any>;
  assert.deepEqual(Post.objects.chain(), ["b", "a"]);
  assert.deepEqual(Post.objects.everything().chain(), ["b", "a"]);
});

test("the user query set class comes first, then the extension classes", () => {
  const p = project();
  const records = [...p.records, record("ext.b", p.hash, { query_set_members: ["chain"], instance_members: [], overrides: ["chain"] })];
  const extensions = { ...code(p), "ext.b": { module: { queries: mixinB, Instance: class {} }, hash: p.hash, dir: new URL("file:///nowhere/") } };
  class Queries extends QuerySet<never> {
    chain(): string[] {
      // @ts-expect-error the member comes from an extension mixin
      return ["user", ...super.chain()];
    }
  }
  const { Post } = build(records, extensions, { Post: ["ext.a", "ext.b"] }) as Record<string, any>;
  useQuerySet(Post, Queries);
  assert.deepEqual(Post.objects.chain(), ["user", "b", "a"]);
  assert.equal(Post.objects.constructor, Queries);
});

test("a user query set class shared with a model that has other extensions fails", () => {
  const p = project();
  class Queries extends QuerySet<never> {}
  const { Post, Tag } = build(p.records, code(p), { Post: ["ext.a"] }) as Record<string, any>;
  useQuerySet(Post, Queries);
  useQuerySet(Tag, Queries);
  assert.equal(typeof Post.objects.everything, "function");
  assert.throws(() => Tag.objects, /Tag: the query set class Queries is shared with a model that has extensions/);
});

test("an instance override calls super down the chain to the host member", () => {
  const p = project();
  const records = [
    record("ext.a", p.hash, { query_set_members: [], instance_members: ["toJSON"], overrides: ["toJSON"] }),
    record("ext.b", p.hash, { query_set_members: [], instance_members: ["toJSON"], overrides: ["toJSON"] }),
  ];
  const instance = (tag: string) => class extends InstanceBase<{ toJSON(): object }> {
    override toJSON() { return { ...super.toJSON(), [tag]: true }; }
  };
  const none = (Base: Ctor) => class extends Base {};
  const extensions = {
    "ext.a": { module: { queries: none, Instance: instance("a") }, hash: p.hash, dir: p.dir },
    "ext.b": { module: { queries: none, Instance: instance("b") }, hash: p.hash, dir: new URL("file:///nowhere/") },
  };
  const { Post, Tag } = build(records, extensions, { Post: ["ext.a", "ext.b"], Tag: ["ext.a"] }) as Record<string, any>;
  assert.deepEqual(Object.create(Post._meta.Row.prototype).toJSON(), { a: true, b: true });
  assert.deepEqual(Object.create(Tag._meta.Row.prototype).toJSON(), { a: true });
});

test("an undeclared collision fails at define", () => {
  const p = project("ext.a", { query_set_members: ["filter"], instance_members: [] });
  assert.throws(() => build(p.records, code(p), { Post: ["ext.a"] }), /Post\.filter: extension ext\.a query set member collides with a host member; declare it as an override/);
  const q = project("ext.a", { query_set_members: [], instance_members: ["title"], overrides: ["title"] });
  assert.throws(() => build(q.records, code(q), { Post: ["ext.a"] }), /Post\.title: .* field or a relation/);
});

test("two extensions with one name collide unless overridden", () => {
  const p = project();
  const records = [...p.records, record("ext.b", p.hash, { query_set_members: ["chain"], instance_members: [] })];
  const extensions = { ...code(p), "ext.b": { module: { queries: mixinB, Instance: class {} }, hash: p.hash, dir: new URL("file:///nowhere/") } };
  assert.throws(() => build(records, extensions, { Post: ["ext.a", "ext.b"] }), /Post\.chain: extension ext\.b query set member collides with a member of extension ext\.a/);
});

test("a changed generated file fails at define", () => {
  const p = project();
  const path = join(p.root, "ext-a", "index.ts");
  writeFileSync(path, readFileSync(path, "utf8") + "\nexport const b = 2;\n");
  assert.throws(() => build(p.records, code(p), { Post: ["ext.a"] }), /were edited; run `orm generate`/);
});

test("code from another build fails at define", () => {
  const p = project();
  assert.throws(() => build(p.records, code({ hash: "0".repeat(64), dir: p.dir }), { Post: ["ext.a"] }), /made for another build; run `orm generate`/);
});

test("no extension changes nothing", () => {
  const { Post } = define(call(() => native().compileSchema(source, null)), { registry: new Registry() }) as Record<string, any>;
  assert.equal(Object.getPrototypeOf(Post.objects).constructor, QuerySet);
});
