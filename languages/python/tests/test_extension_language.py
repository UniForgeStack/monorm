"""Extension language code at runtime: composition, member rules and the generated-file check.

The default native artifact has no extension, so the artifact record is faked; the
files and `define()` are real.
"""

import importlib
import sys

import pytest

import orm
from orm import _extensions, _native
from orm.model import define

SOURCE = """
model Post {
  id Int @id
  title String
}
model Tag {
  id Int @id
}
"""

BASE = """\
from orm import QuerySet
from orm.ext import ModelT


class AQuerySet(QuerySet[ModelT]):
    def everything(self):
        return self.without_defaults()

    def chain(self):
        return ["a"]


class AInstance:
    def label(self):
        return f"a{self.pk}"
"""

SECOND = """\
from orm import QuerySet
from orm.ext import ModelT


class BQuerySet(QuerySet[ModelT]):
    def chain(self):
        return ["b", *super().chain()]


class BInstance:
    def label(self):
        return "b" + super().label()
"""


def record(extension, files, **changes):
    version = "1.0.0"
    out = {
        "extension": extension,
        "version": version,
        "language": "python",
        "query_set": "AQuerySet",
        "instance": "AInstance",
        "query_set_members": ["chain", "everything"],
        "instance_members": ["label"],
        "bound_query_set": "",
        "bound_query_set_members": [],
        "overrides": [],
        "hash": _extensions._digest([(name, text.encode()) for name, text in files.items()]),
    }
    out.update(changes)
    return out


def write(root, package, extension, files, record):
    folder = root / package
    folder.mkdir(parents=True, exist_ok=True)
    header = f"# Generated by `orm generate` from extension {extension}. Do not edit.\n# orm-ext {extension} {record['version']} {record['hash']}\n\n"
    for name, text in files.items():
        (folder / name).write_text(header + text)
    return folder


@pytest.fixture
def project(tmp_path, monkeypatch):
    (tmp_path / "orm_ext").mkdir()
    (tmp_path / "orm_ext" / "__init__.py").write_text("")
    monkeypatch.syspath_prepend(str(tmp_path))
    # An artifact session can hold the real generated `orm_ext` package; this test needs its own.
    saved = {n: m for n, m in sys.modules.items() if n == "orm_ext" or n.startswith("orm_ext.")}
    for name in saved:
        del sys.modules[name]
    before = set(sys.modules)
    yield tmp_path
    for name in set(sys.modules) - before:
        del sys.modules[name]
    sys.modules.update(saved)
    importlib.invalidate_caches()


def install(project, monkeypatch, *specs):
    records = {}
    modules = {}
    for extension, package, files, changes in specs:
        rec = record(extension, files, **changes)
        write(project / "orm_ext", package, extension, files, rec)
        records[extension] = rec
        modules[extension] = importlib.import_module(f"orm_ext.{package}")
    monkeypatch.setattr(_extensions, "records", lambda: records)
    return modules, records


def build(modules, members, source=SOURCE):
    return define(_native.compile_schema(source), registry=orm.Registry(), extensions=modules, members=members)


def test_members_reach_only_the_models_that_use_the_extension(project, monkeypatch):
    modules, _ = install(project, monkeypatch, ("ext.a", "ext_a", {"__init__.py": BASE}, {}))
    out = build(modules, {"Post": ("ext.a",)})
    assert out["Post"].objects.chain() == ["a"]
    assert out["Post"].objects.everything()._model is out["Post"]
    assert not hasattr(out["Tag"].objects, "chain")
    assert not hasattr(out["Tag"], "label")
    assert "label" in dir(out["Post"])


def test_two_mixins_chain_through_super_in_dependency_order(project, monkeypatch):
    modules, _ = install(
        project,
        monkeypatch,
        ("ext.a", "ext_a", {"__init__.py": BASE}, {}),
        (
            "ext.b",
            "ext_b",
            {"__init__.py": SECOND},
            {
                "query_set": "BQuerySet",
                "instance": "BInstance",
                "query_set_members": ["chain"],
                "instance_members": ["label"],
                "overrides": ["chain", "label"],
            },
        ),
    )
    Post = build(modules, {"Post": ("ext.a", "ext.b")})["Post"]
    assert Post.objects.chain() == ["b", "a"]
    assert Post.objects.everything().chain() == ["b", "a"]
    assert [c.__name__ for c in type(Post.objects).__mro__[:3]] == ["PostQuerySet", "BQuerySet", "AQuerySet"]


def test_declared_instance_overrides_call_super_to_the_host(project, monkeypatch):
    def instance_source(tag):
        return f'''from orm import QuerySet
from orm.ext import ModelT
class AQuerySet(QuerySet[ModelT]):
    pass
class AInstance:
    def to_dict(self):
        result = super().to_dict()
        return {{**result, "calls": [*result.get("calls", []), "{tag}"]}}
'''

    changes = {"query_set_members": [], "instance_members": ["to_dict"], "overrides": ["to_dict"]}
    modules, _ = install(
        project,
        monkeypatch,
        ("ext.a", "ext_a", {"__init__.py": instance_source("a")}, changes),
        ("ext.b", "ext_b", {"__init__.py": instance_source("b")}, changes),
    )
    out = build(modules, {"Post": ("ext.a", "ext.b"), "Tag": ("ext.a",)})
    post = object.__new__(out["Post"])
    post.__dict__.update(id=1, title="hello")
    tag = object.__new__(out["Tag"])
    tag.__dict__.update(id=2)
    assert post.to_dict() == {"id": 1, "title": "hello", "calls": ["a", "b"]}
    assert tag.to_dict() == {"id": 2, "calls": ["a"]}


def test_user_query_set_comes_first(project, monkeypatch):
    modules, _ = install(project, monkeypatch, ("ext.a", "ext_a", {"__init__.py": BASE}, {}))

    class Mine(orm.QuerySet):
        def chain(self):
            return ["mine", *super().chain()]

    Post = build(modules, {"Post": ("ext.a",)})["Post"]
    orm.use_query_set(Post, Mine)
    assert Post.objects.chain() == ["mine", "a"]


def test_undeclared_collision_fails_at_define(project, monkeypatch):
    clash = BASE.replace("def everything", "def where").replace(
        'def chain(self):\n        return ["a"]', "def filter(self):\n        return 1"
    )
    modules, _ = install(
        project,
        monkeypatch,
        ("ext.a", "ext_a", {"__init__.py": clash}, {"query_set_members": ["filter", "where"], "instance_members": []}),
    )
    with pytest.raises(TypeError, match=r"Post\.filter: extension ext\.a query set member collides with a host member"):
        build(modules, {"Post": ("ext.a",)})
    field = BASE.replace("def label", "def title")
    modules, _ = install(
        project,
        monkeypatch,
        ("ext.f", "ext_f", {"__init__.py": field}, {"instance_members": ["title"], "overrides": ["title"]}),
    )
    with pytest.raises(TypeError, match=r"Post\.title: .* field or a relation"):
        build(modules, {"Post": ("ext.f",)})


BOUND = (
    BASE
    + """
from orm import BoundQuerySet


class ABound(BoundQuerySet[ModelT]):
    def everything(self):
        return self._clone(self._qs.without_defaults())

    def update(self, **values):
        return super().update(**values)
"""
)


def test_a_bound_member_collides_with_a_host_member_unless_overridden(project, monkeypatch):
    changes = {"bound_query_set": "ABound", "bound_query_set_members": ["everything", "update"]}
    modules, _ = install(project, monkeypatch, ("ext.a", "ext_a", {"__init__.py": BOUND}, changes))
    with pytest.raises(
        TypeError, match=r"Post\.update: extension ext\.a bound query set member collides with a host member"
    ):
        build(modules, {"Post": ("ext.a",)})


def test_a_bound_class_is_composed_from_the_extensions(project, monkeypatch):
    changes = {
        "bound_query_set": "ABound",
        "bound_query_set_members": ["everything", "update"],
        "overrides": ["update"],
    }
    modules, _ = install(project, monkeypatch, ("ext.a", "ext_a", {"__init__.py": BOUND}, changes))
    out = build(modules, {"Post": ("ext.a",), "Tag": ()})
    post = object.__new__(out["Post"])
    post.__dict__.update(id=1, title="hello")
    bound = out["Post"].objects.of(post)
    assert [c.__name__ for c in type(bound).__mro__[:3]] == ["PostBoundQuerySet", "ABound", "BoundQuerySet"]
    assert type(bound.everything()) is type(bound) and type(bound.filter()) is type(bound)
    tag = object.__new__(out["Tag"])
    tag.__dict__.update(id=2)
    assert type(out["Tag"].objects.of(tag)) is orm.BoundQuerySet
    assert not hasattr(out["Tag"].objects.of(tag), "everything")


def test_two_extensions_with_one_name_collide_unless_overridden(project, monkeypatch):
    modules, _ = install(
        project,
        monkeypatch,
        ("ext.a", "ext_a", {"__init__.py": BASE}, {}),
        (
            "ext.b",
            "ext_b",
            {"__init__.py": SECOND},
            {
                "query_set": "BQuerySet",
                "instance": "BInstance",
                "query_set_members": ["chain"],
                "instance_members": ["label"],
            },
        ),
    )
    with pytest.raises(
        TypeError, match=r"Post\.chain: extension ext\.b query set member collides with a member of extension ext\.a"
    ):
        build(modules, {"Post": ("ext.a", "ext.b")})


def test_a_changed_generated_file_fails_at_define(project, monkeypatch):
    modules, _ = install(project, monkeypatch, ("ext.a", "ext_a", {"__init__.py": BASE}, {}))
    path = project / "orm_ext" / "ext_a" / "__init__.py"
    path.write_text(path.read_text() + "\nx = 1\n")
    with pytest.raises(TypeError, match=r"were edited; run `orm generate`"):
        build(modules, {"Post": ("ext.a",)})


def test_a_file_from_another_build_fails_at_define(project, monkeypatch):
    modules, records = install(project, monkeypatch, ("ext.a", "ext_a", {"__init__.py": BASE}, {}))
    monkeypatch.setattr(_extensions, "records", lambda: {"ext.a": {**records["ext.a"], "hash": "0" * 64}})
    with pytest.raises(TypeError, match=r"generated for another build of extension ext\.a; run `orm generate`"):
        build(modules, {"Post": ("ext.a",)})


def test_no_extension_changes_nothing():
    out = define(_native.compile_schema(SOURCE), registry=orm.Registry())
    assert type(out["Post"].objects) is orm.QuerySet
