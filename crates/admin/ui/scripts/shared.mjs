// Writes public/shared/*.js: ES modules that re-export the React of the admin bundle (set on globalThis.__monormAdmin by main.tsx),
// so a bare `import "react"` in a package module resolves, through the import map, to the one React of the page.
// The export lists come from the installed packages, so they always match the bundled version.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const out = new URL("../public/shared/", import.meta.url);
mkdirSync(out, { recursive: true });

function shim(file, global, specifier, { defaultExport }) {
  const names = Object.keys(require(specifier)).filter((n) => n !== "default" && /^[A-Za-z_$][\w$]*$/.test(n) && !n.startsWith("__")).sort();
  const lines = [`// Generated by scripts/shared.mjs from ${specifier}. Do not edit.`, `const M = globalThis.__monormAdmin.${global};`];
  if (defaultExport) lines.push("export default M;");
  for (const n of names) lines.push(`export const ${n} = M.${n};`);
  writeFileSync(new URL(file, out), lines.join("\n") + "\n");
}

shim("react.js", "React", "react", { defaultExport: true });
shim("jsx-runtime.js", "jsxRuntime", "react/jsx-runtime", { defaultExport: false });
shim("react-dom.js", "ReactDOM", "react-dom", { defaultExport: true });
shim("react-dom-client.js", "ReactDOMClient", "react-dom/client", { defaultExport: false });

// `monorm-admin/ui`: the kit of the admin (src/kit.ts). The names come from its `export { ... } from` blocks;
// the e2e smoke test checks that every name of the shim is a value of the module the bundle sets on `__monormAdmin.ui`.
const kit = readFileSync(new URL("../src/kit.ts", import.meta.url), "utf8").replace(/\/\/.*$/gm, "");
const kitNames = [...kit.matchAll(/export\s*\{([^}]*)\}\s*from/g)].flatMap((m) => m[1].split(",").map((n) => n.trim()).filter(Boolean)).sort();
for (const n of kitNames) if (!/^[A-Za-z_$][\w$]*$/.test(n)) throw new Error(`src/kit.ts: "${n}" is not a plain export name`);
if (new Set(kitNames).size !== kitNames.length) throw new Error("src/kit.ts exports a name twice");
writeFileSync(
  new URL("ui.js", out),
  ["// Generated by scripts/shared.mjs from src/kit.ts. Do not edit.", "const M = globalThis.__monormAdmin.ui;", ...kitNames.map((n) => `export const ${n} = M.${n};`)].join("\n") + "\n",
);
