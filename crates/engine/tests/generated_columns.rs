use monorm_core::{dialect::{Dialect, Target}, dsl, ir::{Operation, ValueType}};
use monorm_engine::{db::{self, Cell}, exec::{self, Conflict, Outcome}, params::NoParams, plan::Planner, Params, Result};
use sea_query::Value;
use serde_json::json;

const SOURCE: &str = r#"
model Line {
 id Int @id
 quantity Int
 price Int
 total Int @generated(quantity * price)
 @@map("generated_lines")
}
"#;

fn compile(dialect: Dialect) -> monorm_core::schema::Schema {
    let source = if dialect == Dialect::Sqlite { format!("datasource db {{\n provider = \"sqlite\"\n}}\n{SOURCE}") } else { SOURCE.to_owned() };
    dsl::check(dsl::compile(&source, None).unwrap()).unwrap().1
}

fn names(fields: &[&str]) -> Vec<String> { fields.iter().map(|f| (*f).to_owned()).collect() }

fn int(n: i32) -> Option<Value> { Some(Value::Int(Some(n))) }

struct One;
impl Params for One {
    fn len(&self) -> usize { 2 }
    fn value(&self, _: usize, _: Option<ValueType>) -> Result<Value> { Ok(Value::Int(Some(1))) }
    fn text(&self, _: usize) -> Result<String> { unreachable!() }
    fn count(&self, _: usize) -> Result<u64> { unreachable!() }
}

fn refusal<T>(result: Result<T>) -> String { result.err().expect("a refusal").to_string() }

#[test]
fn every_write_path_refuses_a_generated_field_before_sql() {
    let schema = compile(Dialect::Postgres);
    let target = Target::new(Dialect::Postgres);
    let wanted = "Line.total is generated by the database; it can't be written";
    let fields = names(&["id", "total"]);
    let row = || vec![vec![int(1), int(2)]];
    assert_eq!(refusal(exec::plan_insert(&schema, target, "Line", &fields, row(), None, &NoParams, &Default::default())), wanted);
    let upsert = Conflict::Update { target: names(&["id"]), index: Default::default(), update: names(&["total"]), set: vec![] };
    assert_eq!(refusal(exec::plan_insert(&schema, target, "Line", &names(&["id"]), vec![vec![int(1)]], Some(upsert), &NoParams, &Default::default())), wanted);
    let rows = vec![vec![Value::Int(Some(1)), Value::Int(Some(2))]];
    assert_eq!(refusal(exec::plan_update_many(&schema, target, "Line", &fields, rows, &[], &NoParams, false, None, &Default::default())), wanted);
    assert_eq!(refusal(exec::plan_copy(&schema, target, "Line", &fields, row())), wanted);
    let op: Operation = serde_json::from_value(json!({"op":"update","model":"Line","filters":[],"set":[{"field":"total","value":{"t":"param","i":0}}]})).unwrap();
    assert_eq!(refusal(Planner::plan(&schema, target, &op, &One)), wanted);
}

async fn returns_the_generated_value(url: &str, dialect: Dialect) {
    let schema = compile(dialect);
    let target = Target::new(dialect);
    let db = db::connect(url, 1).await.unwrap();
    let conn = db.begin().await.unwrap();
    for statement in monorm_core::migrate::create_all(&schema).unwrap() { conn.batch(statement).await.unwrap(); }
    let types: Vec<ValueType> = schema.model(schema.model_idx("Line").unwrap()).fields().iter().map(|f| f.value_type()).collect();
    let plan = exec::plan_insert(&schema, target, "Line", &names(&["id", "quantity", "price"]), vec![vec![int(1), int(3), int(4)], vec![int(2), int(5), int(6)]], None, &NoParams, &Default::default()).unwrap();
    let Outcome::Rows { rows, .. } = exec::run(conn.as_ref(), target, plan).await.unwrap() else { panic!() };
    assert_eq!(rows.cell(0, 3, types[3]).unwrap(), Cell::Int(12));
    assert_eq!(rows.cell(1, 3, types[3]).unwrap(), Cell::Int(30));
    conn.rollback().await.unwrap();
    db.close().await;
}

#[test]
fn sqlite_insert_returns_the_generated_value() {
    tokio::runtime::Runtime::new().unwrap().block_on(returns_the_generated_value("sqlite://:memory:", Dialect::Sqlite));
}

#[test]
fn postgres_insert_returns_the_generated_value() {
    let url = std::env::var("ORM_RUST_TEST_POSTGRES_URL").or_else(|_| std::env::var("ORM_TEST_DATABASE_URL")).unwrap_or_else(|_| "postgres://postgres:postgres@localhost/orm_test".into());
    tokio::runtime::Runtime::new().unwrap().block_on(returns_the_generated_value(&url, Dialect::Postgres));
}
